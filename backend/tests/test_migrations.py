import os
import uuid

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url

from app.migrate import apply_migrations


def test_sqlite_bootstrap_creates_40_character_transaction_type(tmp_path):
    database = tmp_path / "migration-test.sqlite"
    test_engine = create_engine(f"sqlite:///{database}")

    with test_engine.begin() as connection:
        apply_migrations(connection)
        column = next(
            column
            for column in connection.exec_driver_sql("PRAGMA table_info(credit_transactions)")
            if column["name"] == "transaction_type"
        )
        connection.execute(
            text(
                "INSERT INTO credit_transactions "
                "(household_id, energy_kwh, credits, transaction_type) "
                "VALUES ('HH-001', 1.0, 10.0, :transaction_type)"
            ),
            {"transaction_type": "community_contribution"},
        )
        saved = connection.execute(
            text("SELECT transaction_type FROM credit_transactions")
        ).scalar_one()

    assert column["type"].upper() == "VARCHAR(40)"
    assert saved == "community_contribution"
    test_engine.dispose()


def test_postgresql_migration_is_idempotent_and_preserves_existing_rows():
    database_url = os.getenv("ECOPULSE_TEST_DATABASE_URL")
    if not database_url:
        pytest.skip("Set ECOPULSE_TEST_DATABASE_URL to an isolated PostgreSQL test database.")

    parsed_url = make_url(database_url)
    assert parsed_url.get_backend_name() in {"postgres", "postgresql"}, (
        "ECOPULSE_TEST_DATABASE_URL must point to PostgreSQL."
    )
    assert "test" in (parsed_url.database or "").lower(), (
        "Refusing to run the migration integration test unless the database name includes 'test'."
    )

    test_engine = create_engine(database_url)
    schema_name = f"ecopulse_migration_test_{uuid.uuid4().hex}"
    quote = test_engine.dialect.identifier_preparer.quote

    # All DDL/data are scoped to a unique schema and rolled back. No production tables are touched.
    with test_engine.connect() as connection:
        transaction = connection.begin()
        try:
            connection.exec_driver_sql(f"CREATE SCHEMA {quote(schema_name)}")
            connection.exec_driver_sql(f"SET LOCAL search_path TO {quote(schema_name)}")
            connection.exec_driver_sql(
                """
                CREATE TABLE credit_transactions (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    timestamp timestamp with time zone NOT NULL DEFAULT now(),
                    simulation_id integer,
                    household_id varchar(40) NOT NULL,
                    energy_kwh double precision NOT NULL,
                    credits double precision NOT NULL,
                    transaction_type varchar(20) NOT NULL
                )
                """
            )
            connection.execute(
                text(
                    "INSERT INTO credit_transactions "
                    "(household_id, energy_kwh, credits, transaction_type) "
                    "VALUES ('HH-LEGACY', 1, 10, 'community')"
                )
            )

            apply_migrations(connection)
            length = connection.execute(
                text(
                    "SELECT character_maximum_length FROM information_schema.columns "
                    "WHERE table_schema = current_schema() "
                    "AND table_name = 'credit_transactions' "
                    "AND column_name = 'transaction_type'"
                )
            ).scalar_one()
            assert length == 40

            connection.execute(
                text(
                    "INSERT INTO credit_transactions "
                    "(household_id, energy_kwh, credits, transaction_type) "
                    "VALUES ('HH-002', 1, 10, 'community_contribution')"
                )
            )
            # Re-running the same migration must be harmless and must not alter existing data.
            apply_migrations(connection)
            rows = connection.execute(
                text("SELECT household_id, transaction_type FROM credit_transactions ORDER BY id")
            ).all()
            assert rows == [
                ("HH-LEGACY", "community"),
                ("HH-002", "community_contribution"),
            ]
        finally:
            transaction.rollback()
            connection.close()
            test_engine.dispose()
